/**
 * UI 표시용 날짜 포맷터
 * * @param date 포맷팅할 Date 객체
 * @returns "YYYY. MM. DD. HH:mm:ss" 형식의 문자열 (예: "2025. 01. 01. 12:30:05")
 */
export default function formatDateToDisplay(date: Date): string {
	// =========================================================================================
	// 1. 내부 헬퍼 함수: 제로 패딩 (Zero Padding)
	// =========================================================================================
	// 숫자가 10보다 작을 경우 앞에 '0'을 붙여 2자리 문자열로 만듭니다.
	// 예: 5 -> "05", 12 -> "12"
	const pad = (n: number) => n.toString().padStart(2, "0");

	// =========================================================================================
	// 2. 날짜 및 시간 요소 추출
	// =========================================================================================
	const year = date.getFullYear();

	// [중요] JavaScript의 getMonth()는 0부터 시작하므로(0=1월), 반드시 +1을 해줘야 합니다.
	const month = pad(date.getMonth() + 1);

	const day = pad(date.getDate());
	const hour = pad(date.getHours());
	const min = pad(date.getMinutes());
	const sec = pad(date.getSeconds());

	// =========================================================================================
	// 3. 최종 포맷팅 문자열 반환
	// =========================================================================================
	// 가독성을 위해 날짜는 점(.)으로, 시간은 콜론(:)으로 구분합니다.
	return `${year}. ${month}. ${day}. ${hour}:${min}:${sec}`;
}
